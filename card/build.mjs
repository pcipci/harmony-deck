// Bundles the card sources (src/) into the single file that Home Assistant loads.
//   npm run build        -> ../custom_components/harmony_deck/frontend/harmony-deck-card.js
//   node build.mjs <out> -> another target (used by the regression check)
import { build } from "esbuild";
import { fileURLToPath } from "url";
import path from "path";

const here = path.dirname(fileURLToPath(import.meta.url));
const outfile = process.argv[2] || path.join(here, "..", "custom_components", "harmony_deck", "frontend", "harmony-deck-card.js");

await build({
  entryPoints: [path.join(here, "src", "index.js")],
  bundle: true,
  format: "iife",
  target: "es2021",
  charset: "utf8",
  legalComments: "inline",
  banner: { js: "/* Harmony Deck: built from card/src (see card/README.md). Do not edit this file, edit the sources and run `npm run build`. */" },
  outfile,
  logLevel: "info",
});
